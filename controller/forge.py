"""
Bridge between the Streamlit pages and the fast-stack-forge package.

The option lists shown in the forms are read from the installed package, so the
app stays in sync with the CLI. Projects are generated by running the real CLI
in a temporary folder and zipping the result.
"""
import html
import io
import json
import os
import shlex
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

import streamlit as st

try:
    import fast_stack_forge
    from fast_stack_forge.cli import cli
    from fast_stack_forge.commands.init import DB_HELP
    from fast_stack_forge.commands.init_dbt import ARCHITECTURES, ADAPTERS, PYTHON_VERSIONS as DBT_PYTHON_VERSIONS
    from fast_stack_forge.commands.init_databricks import RUNTIMES, NODE_TYPES, COMPONENTS
    from fast_stack_forge.commands.init_ds_data import DB_CHOICES, get_python_versions
    from fast_stack_forge.commands.make_service import SERVICE_TYPES, PROVIDERS, VECTOR_STORES
    from fast_stack_forge.utils import sanitize_name
except ImportError:  # handled by require_package()
    fast_stack_forge = None

PYPI_URL = "https://pypi.org/project/fast-stack-forge/"
LICENSES = ["MIT", "BSD-3-Clause", "Apache-2.0", "GPL-3.0"]

# The CLI asks questions for options that have no flag (Python version, author, ...).
# Prompts are answered from FSF_ANSWERS, matched on a fragment of the question label.
_DRIVER = """
import json, os, sys
from fast_stack_forge import utils

answers = json.loads(os.environ.get("FSF_ANSWERS") or "{}")

def answer(label, default):
    for fragment, value in answers.items():
        if fragment.lower() in label.lower():
            return value
    return default

def choice(self, label, options, default=None):
    values = [o[0] if isinstance(o, tuple) else o for o in options]
    value = answer(label, default)
    return value if value in values else (default if default in values else values[0])

utils.Prompter.text = lambda self, label, default="": str(answer(label, default))
utils.Prompter.confirm = lambda self, label, default=False: bool(answer(label, default))
utils.Prompter.choice = choice

from fast_stack_forge.cli import main
sys.argv[0] = "fast-stack-forge"
main()
"""


def require_package() -> None:
    """Stop the page with install instructions when fast-stack-forge is missing."""
    if fast_stack_forge is None:
        st.error("fast-stack-forge isn't installed in this environment, so projects can't be generated.")
        st.code(f'"{sys.executable}" -m pip install -U fast-stack-forge', language="bash")
        st.stop()


def version() -> str:
    return fast_stack_forge.__version__ if fast_stack_forge else "not installed"


def public_commands() -> list:
    """(name, first help line) for every visible CLI command."""
    if fast_stack_forge is None:
        return []
    return [
        (name, (cmd.help or "").strip().splitlines()[0])
        for name, cmd in cli.commands.items()
        if not cmd.hidden
    ]


def command_line(args: list) -> str:
    return shlex.join(["fast-stack-forge", *args])


def generate(args: list, answers: dict, name: str) -> dict:
    """Run the CLI in a temporary folder and return its output and the zipped project."""
    with tempfile.TemporaryDirectory() as tmp:
        result = subprocess.run(
            [sys.executable, "-c", _DRIVER, *args],
            cwd=tmp,
            capture_output=True,
            text=True,
            timeout=120,
            env={**os.environ, "FSF_ANSWERS": json.dumps(answers), "NO_COLOR": "1"},
        )
        files = sorted(p.relative_to(tmp) for p in Path(tmp).rglob("*") if p.is_file())
        archive = None
        if result.returncode == 0 and files:
            buffer = io.BytesIO()
            with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zf:
                for rel in files:
                    zf.write(Path(tmp) / rel, rel)
            archive = buffer.getvalue()
    return {
        "ok": archive is not None,
        "output": (result.stdout + result.stderr).strip(),
        "files": [str(f) for f in files],
        "zip": archive,
        "filename": f"{sanitize_name(name) or 'project'}.zip",
    }


def generate_section(key: str, args: list, answers: dict, name: str, label: str) -> None:
    """Primary button that runs the CLI, then the download button and the file list."""
    options = json.dumps([args, answers])
    if st.button(label, key=f"btn_{key}", type="primary"):
        with st.spinner("Running fast-stack-forge…"):
            st.session_state[f"result_{key}"] = {**generate(args, answers, name), "options": options}

    result = st.session_state.get(f"result_{key}")
    if not result:
        return
    if result["options"] != options:  # the form changed since: don't offer a stale project
        st.caption("The options changed since the last run. Generate again to download them.")
        return
    if result["ok"]:
        st.download_button(
            f"Download {result['filename']}",
            result["zip"],
            file_name=result["filename"],
            mime="application/zip",
            key=f"dl_{key}",
        )
        with st.expander(f"{len(result['files'])} files generated"):
            st.code("\n".join(result["files"]), language="text")
    else:
        st.error("The CLI stopped with an error. Its output is below; change the options and generate again.")
    with st.expander("CLI output"):
        st.code(result["output"] or "(no output)", language="text")


# ── HTML building blocks (styled in assets/style.css) ────────────────────────

def terminal(lines: list, title: str = "zsh", animate: bool = False) -> str:
    """A terminal window. Lines starting with '$ ' are commands, others are output.
    A (question, answer) tuple renders a prompt with the typed answer highlighted."""
    body = []
    for i, line in enumerate(lines):
        style = f' style="animation-delay:{0.25 + i * 0.12:.2f}s"' if animate else ""
        if isinstance(line, tuple):
            question, reply = line
            content = f'{html.escape(question)}<span class="t-pick">{html.escape(reply)}</span>'
            body.append(f'<div class="t-line t-out"{style}>{content}</div>')
        elif line.startswith("$ "):
            body.append(f'<div class="t-line"{style}><span class="t-prompt">$</span> <span class="t-cmd">{html.escape(line[2:])}</span></div>')
        else:
            body.append(f'<div class="t-line t-out"{style}>{html.escape(line) or "&nbsp;"}</div>')
    css = "term hero-term" if animate else "term"
    return (
        f'<div class="{css}"><div class="term-bar"><i></i><i></i><i></i><span>{html.escape(title)}</span></div>'
        f'<div class="term-body">{"".join(body)}</div></div>'
    )


def show_terminal(lines: list, title: str = "zsh") -> None:
    st.markdown(terminal(lines, title), unsafe_allow_html=True)


def page_header(title: str, subtitle: str) -> None:
    st.markdown(
        f'<header class="page-head"><h1>{html.escape(title)}</h1><p>{html.escape(subtitle)}</p></header>',
        unsafe_allow_html=True,
    )


